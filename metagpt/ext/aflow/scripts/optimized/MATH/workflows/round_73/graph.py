from typing import Literal
import metagpt.ext.aflow.scripts.optimized.MATH.workflows.template.operator as operator
import metagpt.ext.aflow.scripts.optimized.MATH.workflows.round_73.prompt as prompt_custom
from metagpt.provider.llm_provider_registry import create_llm_instance
from metagpt.utils.cost_manager import CostManager

DatasetType = Literal["HumanEval", "MBPP", "GSM8K", "MATH", "HotpotQA", "DROP", "MMLU"]

class Workflow:
    def __init__(
        self,
        name: str,
        llm_config,
        dataset: DatasetType,
    ) -> None:
        self.name = name
        self.dataset = dataset
        self.llm = create_llm_instance(llm_config)
        self.llm.cost_manager = CostManager()
        self.custom = operator.Custom(self.llm)
        self.programmer = operator.Programmer()

    async def __call__(self, problem: str):
        """
        Implementation of the workflow
        """
        # Generate a solution using the custom method
        solution = await self.custom(input=problem, instruction="")
        
        # Validate the solution using the programmer operator
        validation_code = f"def validate_solution():\n    return {solution['response']}  # Placeholder for actual validation logic"
        validation_result = await self.programmer(problem=validation_code)
        
        # Return the solution and validation result
        return solution['response'], validation_result['output'], self.llm.cost_manager.total_cost
